def extract_words(txt_path):

    words = []
    current_word = []

    with open(txt_path, "r") as f:
        lines = f.readlines()

    for line in lines:

        line = line.strip()

        if line == "":
            continue

        parts = line.split()

        if len(parts) != 2:
            continue

        phone = parts[0]
        score = float(parts[1])

        if phone == "SIL":
            continue

        # Beginning of word
        if phone.endswith("_B"):

            if len(current_word) > 0:
                words.append(current_word)

            current_word = [score]

        # Inside word
        elif phone.endswith("_I"):

            current_word.append(score)

        # End of word
        elif phone.endswith("_E"):

            current_word.append(score)
            words.append(current_word)
            current_word = []

    if len(current_word) > 0:
        words.append(current_word)

    return words

