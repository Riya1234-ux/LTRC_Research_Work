def compute_word_features(scores):

    scores = np.array(scores, dtype=float)

    if len(scores) == 0:
        return None

    sorted_scores = np.sort(scores)

    q10 = np.percentile(scores,10)
    q25 = np.percentile(scores,25)
    q75 = np.percentile(scores,75)
    q90 = np.percentile(scores,90)

    return {

        # Existing
        "mean_gop": np.mean(scores),
        "median_gop": np.median(scores),
        "min_gop": np.min(scores),
        "max_gop": np.max(scores),
        "std_gop": np.std(scores),
        "variance_gop": np.var(scores),
        "range_gop": np.ptp(scores),

        # Counts
        "phoneme_count": len(scores),
        "negative_count": np.sum(scores < 0),
        "negative_ratio": np.mean(scores < 0),
        "below2_count": np.sum(scores < 2),
        "below4_count": np.sum(scores < 4),
        "below6_count": np.sum(scores < 6),
        "below8_count": np.sum(scores < 8),

        # Bottom / Top
        "bottom1": sorted_scores[0],
        "bottom2_avg": np.mean(sorted_scores[:min(2,len(scores))]),
        "bottom3_avg": np.mean(sorted_scores[:min(3,len(scores))]),
        "bottom_half_avg": np.mean(sorted_scores[:max(1,len(scores)//2)]),

        "top1": sorted_scores[-1],
        "top2_avg": np.mean(sorted_scores[-min(2,len(scores)):]),
        "top3_avg": np.mean(sorted_scores[-min(3,len(scores)):]),

        # Percentiles
        "p10": q10,
        "p25": q25,
        "p75": q75,
        "p90": q90,

        # Spread
        "iqr": q75-q25,
        "mean_abs_dev": np.mean(np.abs(scores-np.mean(scores))),
        "rms_gop": np.sqrt(np.mean(scores**2)),
        "coeff_var": np.std(scores)/(np.mean(scores)+1e-6),

        # Shape
        "skewness": skew(scores) if len(scores)>2 else 0,
        "kurtosis": kurtosis(scores) if len(scores)>3 else 0,

        # Good vs Bad
        "good_ratio": np.mean(scores>6),
        "excellent_ratio": np.mean(scores>8),
        "poor_ratio": np.mean(scores<4),

        # Difference
        "max_min_gap": np.max(scores)-np.min(scores),
        "top_bottom_gap": np.mean(sorted_scores[-2:])-np.mean(sorted_scores[:2]),

        # Trimmed
        "trimmed_mean": np.mean(sorted_scores[1:-1]) if len(scores)>2 else np.mean(scores)
    }

